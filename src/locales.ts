export const LANGS = ["fr", "en", "es", "de"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "fr";
export const isLang = (value: unknown): value is Lang => LANGS.includes(value as Lang);

/** Pages publiques : clé interne → slug (identique dans toutes les langues). */
export const PAGES = {
  home: "",
  portfolio: "portfolio",
  catalogue: "catalogue",
  about: "a-propos",
  location: "ou-nous-trouver",
  contact: "contact",
  quote: "devis",
  mentions: "mentions-legales",
  privacy: "confidentialite",
  terms: "cgv",
  cookies: "cookies",
} as const;
export type PageKey = keyof typeof PAGES;
export type LegalKey = "mentions" | "privacy" | "terms" | "cookies";

/** Chemin localisé : le français reste à la racine, les autres langues sont préfixées. */
export const localePath = (lang: Lang, page: PageKey | string = "home") => {
  const slug = page in PAGES ? PAGES[page as PageKey] : String(page).replace(/^\//, "");
  const prefix = lang === DEFAULT_LANG ? "" : `/${lang}`;
  return `${prefix}/${slug}`.replace(/\/$/, "") || "/";
};

/** Découpe une URL en langue + clé de page. */
export const parsePath = (pathname: string): { lang: Lang; page: PageKey | null } => {
  const parts = pathname.split("/").filter(Boolean);
  const lang = isLang(parts[0]) && parts[0] !== DEFAULT_LANG ? parts.shift()! : DEFAULT_LANG;
  const slug = parts.join("/");
  const page = (Object.keys(PAGES) as PageKey[]).find((key) => PAGES[key] === slug) ?? null;
  return { lang: lang as Lang, page };
};

